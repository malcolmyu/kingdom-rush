"""Lossless audited desktop map crops; no mod controller or gameplay executed."""
import hashlib,json,pathlib,urllib.request,urllib.parse
from PIL import Image
ROOT=pathlib.Path(__file__).resolve().parents[1]
s=json.loads((ROOT/'tools/sources/desktop-map.json').read_text());out=ROOT/'web/assets/desktop-map';out.mkdir(exist_ok=True)
base=s['repository'].replace('github.com','raw.githubusercontent.com')+'/'+s['commit']+'/'
sheets={}
for name,sha in s['sheets'].items():
 p=ROOT/'artifacts'/('kro-'+name)
 data=p.read_bytes() if p.exists() else urllib.request.urlopen(base+'kr3-desktop/assets/images/fullhd/'+name,timeout=60).read()
 if hashlib.sha256(data).hexdigest()!=sha:raise RuntimeError('Map source checksum: '+name)
 p.write_bytes(data);sheets[name]=Image.open(p).convert('RGBA')
frames={};large={};width=1024;x=y=row=0;tiles=[]
for key,f in sorted(s['frames'].items()):
 if key.startswith('map_flag_') and key[9:].isdigit() and int(key[9:]) not in {*range(1,25),64,134,179,180,181,182}:continue
 qx,qy,w,h=f['f_quad'];im=sheets[f['a_name']].crop((qx,qy,qx+w,qy+h))
 if key.startswith('map_background'):
  name=key+'.webp';im.save(out/name,lossless=True,exact=True,method=6)
  if Image.open(out/name).convert('RGBA').tobytes()!=im.tobytes():raise RuntimeError(key)
  large[key]={'src':'assets/desktop-map/'+name,'size':f['size'],'trim':f['trim'],'rgbaSha256':hashlib.sha256(im.tobytes()).hexdigest()};continue
 if x+w+2>width:x=0;y+=row+2;row=0
 frames[key]={'q':[x,y,w,h],'size':f['size'],'trim':f['trim']};tiles.append((key,x,y,im));x+=w+2;row=max(row,h)
atlas=Image.new('RGBA',(width,y+row+2))
for key,x,y,im in tiles:atlas.paste(im,(x,y))
atlas.save(out/'sprites.webp',lossless=True,exact=True,method=6);decoded=Image.open(out/'sprites.webp').convert('RGBA')
for key,x,y,im in tiles:
 if decoded.crop((x,y,x+im.width,y+im.height)).tobytes()!=im.tobytes():raise RuntimeError('Packed map pixel mismatch '+key)
catalog={'provenance':{k:s[k]for k in ['repository','commit','kind','pointsPath','pointsSha256','scope']},'reference':s['reference'],'flags':s['flags'],'roads':s['roads'],'frames':frames,'images':large,'sheet':'assets/desktop-map/sprites.webp'}
(out/'catalog.json').write_text(json.dumps(catalog,ensure_ascii=False,separators=(',',':')))
(ROOT/'web/desktop-map-data.mjs').write_text('// Audited declaration data, generated by extract_desktop_map.py.\nexport default '+json.dumps({'reference':s['reference'],'flags':s['flags'],'roads':s['roads']},separators=(',',':'))+';\n')
print('Desktop map:',len(frames),'packed frames,',sum(p.stat().st_size for p in out.iterdir()),'bytes')
