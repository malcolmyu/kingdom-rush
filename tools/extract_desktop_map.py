"""Lossless audited desktop map crops; no mod controller or gameplay executed."""
import hashlib,json,pathlib,urllib.request
from PIL import Image
ROOT=pathlib.Path(__file__).resolve().parents[1]
s=json.loads((ROOT/'tools/sources/desktop-map.json').read_text());out=ROOT/'web/assets/desktop-map';out.mkdir(exist_ok=True)
base=s['repository'].replace('github.com','raw.githubusercontent.com')+'/'+s['commit']+'/'
sheets={}
for name,sha in s['sheets'].items():
 p=ROOT/'artifacts'/('kro-'+name);raw=p.read_bytes()if p.exists()else urllib.request.urlopen(base+'kr3-desktop/assets/images/fullhd/'+name,timeout=60).read()
 if hashlib.sha256(raw).hexdigest()!=sha:raise RuntimeError('Map source checksum: '+name)
 p.write_bytes(raw);sheets[name]=Image.open(p).convert('RGBA')
frames={};large={};groups={}
for key,f in sorted(s['frames'].items()):
 qx,qy,w,h=f['f_quad'];im=sheets[f['a_name']].crop((qx,qy,qx+w,qy+h))
 if key.startswith('map_background'):
  name=key+'.webp';im.save(out/name,lossless=True,exact=True,method=6)
  if Image.open(out/name).convert('RGBA').tobytes()!=im.tobytes():raise RuntimeError(key)
  large[key]={'src':'assets/desktop-map/'+name,'size':f['size'],'trim':f['trim'],'rgbaSha256':hashlib.sha256(im.tobytes()).hexdigest()};continue
 group='sprites'
 if key.startswith('map_flag_')and key[9:].isdigit():
  n=int(key[9:])
  if n not in {*range(1,25),64,134,179,180,181,182}:group=next(('flag-'+mode for mode in ['nostar','campaign','iron']if s['flagMotion']['animations'][mode]['from']<=n<=s['flagMotion']['animations'][mode]['to']),'flag-transition')
 groups.setdefault(group,[]).append((key,f,im))
for group,items in groups.items():
 x=y=row=0;tiles=[];dedup={};src='assets/desktop-map/'+group+'.webp'
 for key,f,im in items:
  w,h=im.size;digest=(w,h,hashlib.sha256(im.tobytes()).hexdigest())
  if digest not in dedup:
   if x+w+2>1024:x=0;y+=row+2;row=0
   dedup[digest]=[x,y,w,h];tiles.append((x,y,im));x+=w+2;row=max(row,h)
  frames[key]={'q':dedup[digest],'size':f['size'],'trim':f['trim'],'sheet':src}
 atlas=Image.new('RGBA',(1024,y+row+2))
 for x,y,im in tiles:atlas.paste(im,(x,y))
 atlas.save(out/(group+'.webp'),lossless=True,exact=True,method=6);decoded=Image.open(out/(group+'.webp')).convert('RGBA')
 for key,f,im in items:
  x,y,w,h=frames[key]['q']
  if decoded.crop((x,y,x+w,y+h)).tobytes()!=im.tobytes():raise RuntimeError('Packed map pixel mismatch '+key)
catalog={'provenance':{k:s[k]for k in ['repository','commit','kind','pointsPath','pointsSha256','scope']},'reference':s['reference'],'hud':s['hud'],'flagMotion':s['flagMotion'],'flags':s['flags'],'roads':s['roads'],'frames':frames,'images':large,'sheet':'assets/desktop-map/sprites.webp','motionSheets':{k:'assets/desktop-map/flag-'+k+'.webp'for k in ['nostar','campaign','iron']}}
(out/'catalog.json').write_text(json.dumps(catalog,ensure_ascii=False,separators=(',',':')))
(ROOT/'web/desktop-map-data.mjs').write_text('// Audited declaration data, generated by extract_desktop_map.py.\nexport default '+json.dumps({k:s[k]for k in ['reference','hud','flagMotion','flags','roads']},separators=(',',':'))+';\n')
print('Desktop map:',len(frames),'packed frames,',sum(p.stat().st_size for p in out.iterdir()),'bytes')
